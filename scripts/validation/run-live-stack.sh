#!/usr/bin/env bash
# A throwaway stack, seeded, so the flows can be run rather than described.
#
# Every validation script in this directory (report, view, escalation, dispatch, p1) assumes
# the same thing: a Postgres with the telrad schema migrated, a bootstrap owner, three readers
# with different grades, an Orthanc node, and an api on 127.0.0.1:3101. None of them can say
# how that came to exist, which meant the recipe lived in one operator's head — and an
# acceptance run nobody can repeat is a claim, not evidence.
#
# This script builds it and takes it away again. It creates its own network and containers
# with `tr-` names, on ports nothing else on this machine uses, with fixture credentials that
# are named as fixtures. It never touches a deployed stack, never publishes a database port
# beyond loopback, and `down` removes everything including the volumes.
#
#   bash scripts/validation/run-live-stack.sh up      # containers, migrations, seed, api
#   source .runtime/live-stack/env.sh                 # the same env the worker and flows need
#   python scripts/validation/run-report-flow.py --phase prepare
#   bash scripts/validation/run-live-stack.sh api-stop && pnpm --filter @telrad/worker once
#   bash scripts/validation/run-live-stack.sh down
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RUNTIME="$ROOT/.runtime/live-stack"
NETWORK=trtest
DB_CONTAINER=tr-ci
DB_PORT=5414
ORTHANC_CONTAINER=tr-orth
ORTHANC_PORT=18042
API_PORT=3101

DB_NAME=telrad
DB_USER=telrad
DB_PASSWORD=live-stack-db-fixture-not-a-real-credential
ORTHANC_PASSWORD=live-stack-orthanc-fixture-not-a-real-credential
SESSION_SECRET=live-stack-session-fixture-not-a-real-secret-0123456789
SIGNING_SECRET=live-stack-signing-fixture-not-a-real-secret-01234567
PASSPHRASE=testonly-passphrase-42

cmd="${1:-}"

say() { echo "── $*"; }

env_file() {
  mkdir -p "$RUNTIME"
  cat >"$RUNTIME/env.sh" <<EOF
# Generated by scripts/validation/run-live-stack.sh. Fixture credentials, throwaway stack.
export TR_DB_URL="postgresql://$DB_USER:$DB_PASSWORD@127.0.0.1:$DB_PORT/$DB_NAME"
export TR_ORTHANC_URL="http://127.0.0.1:$ORTHANC_PORT"
export TR_ORTHANC_USER=orthanc
export TR_ORTHANC_PASSWORD="$ORTHANC_PASSWORD"
export TR_SESSION_SECRET="$SESSION_SECRET"
export TR_UPLOAD_SIGNING_SECRET="$SIGNING_SECRET"
export TR_PUBLIC_URL="http://127.0.0.1:$API_PORT"
export TR_INBOX_ROOT="$RUNTIME/inbox"
export TR_NODE_ID=node-test
export PORT=$API_PORT
export ESC_API="http://127.0.0.1:$API_PORT"
EOF
  mkdir -p "$RUNTIME/inbox"
}

wait_for() {
  local label="$1" tries="$2"; shift 2
  for _ in $(seq 1 "$tries"); do
    if "$@" >/dev/null 2>&1; then say "$label ready"; return 0; fi
    sleep 1
  done
  echo "$label never became ready" >&2
  return 1
}

down() {
  if [ -f "$RUNTIME/api.pid" ]; then
    kill "$(cat "$RUNTIME/api.pid")" 2>/dev/null || true
    rm -f "$RUNTIME/api.pid"
  fi
  docker rm -f "$DB_CONTAINER" "$ORTHANC_CONTAINER" >/dev/null 2>&1 || true
  docker network rm "$NETWORK" >/dev/null 2>&1 || true
  rm -rf "$RUNTIME"
  say "down: containers, network and $RUNTIME removed"
}

status() {
  docker ps -a --filter "name=^/$DB_CONTAINER$" --filter "name=^/$ORTHANC_CONTAINER$" \
    --format '{{.Names}} {{.Status}}'
  if [ -f "$RUNTIME/api.pid" ] && kill -0 "$(cat "$RUNTIME/api.pid")" 2>/dev/null; then
    say "api pid $(cat "$RUNTIME/api.pid") on $API_PORT"
  else
    say "api not running"
  fi
}

api_start() {
  # Stop whatever is listening first. A second `node dist/server.js` dies of EADDRINUSE in
  # the background while the readiness probe answers from the *old* process, and the next
  # person concludes the code they just built does not work. Measured twice on this machine.
  if [ -f "$RUNTIME/api.pid" ]; then
    kill "$(cat "$RUNTIME/api.pid")" 2>/dev/null || true
    rm -f "$RUNTIME/api.pid"
    sleep 2
  fi
  # shellcheck disable=SC1091
  source "$RUNTIME/env.sh"
  (cd "$ROOT/apps/api" && exec node dist/server.js >"$RUNTIME/api.log" 2>&1) &
  echo $! >"$RUNTIME/api.pid"
  sleep 1
  if grep -q EADDRINUSE "$RUNTIME/api.log"; then
    echo "the port is still held by another process; nothing new was started" >&2
    tail -4 "$RUNTIME/api.log" >&2
    return 1
  fi
  wait_for api 30 curl -fs "http://127.0.0.1:$API_PORT/health/ready"
}

case "$cmd" in
down) down; exit 0 ;;
status) status; exit 0 ;;
api-stop)
  if [ -f "$RUNTIME/api.pid" ]; then
    kill "$(cat "$RUNTIME/api.pid")" 2>/dev/null || true
    rm -f "$RUNTIME/api.pid"
    say "api stopped"
  else
    say "no api pid file; nothing to stop"
  fi
  exit 0 ;;
api-start)
  # The containers and the seed stay as they are: after a rebuild this is how the new code
  # gets served without re-running a six-minute ingest.
  api_start; say "api restarted on $API_PORT from the current dist"; exit 0 ;;
up) ;;
*) echo "usage: $0 up|down|status|api-stop|api-start" >&2; exit 2 ;;
esac

DIGEST=$(sed -n 's/^ORTHANC_IMAGE_DIGEST=//p' "$ROOT/.env.example")
[ -n "$DIGEST" ] || { echo "no ORTHANC_IMAGE_DIGEST in .env.example"; exit 1; }

env_file
# shellcheck disable=SC1091
source "$RUNTIME/env.sh"

docker network create "$NETWORK" >/dev/null 2>&1 || true

say "database $DB_CONTAINER on 127.0.0.1:$DB_PORT"
docker rm -f "$DB_CONTAINER" >/dev/null 2>&1 || true
docker run -d --name "$DB_CONTAINER" --network "$NETWORK" -p "127.0.0.1:$DB_PORT:5432" \
  -e POSTGRES_DB="$DB_NAME" -e POSTGRES_USER="$DB_USER" -e POSTGRES_PASSWORD="$DB_PASSWORD" \
  -e TZ=UTC postgres:16-alpine >/dev/null
wait_for database 90 docker exec "$DB_CONTAINER" pg_isready -U "$DB_USER" -d "$DB_NAME"

say "image node $ORTHANC_CONTAINER on 127.0.0.1:$ORTHANC_PORT ($DIGEST)"
docker rm -f "$ORTHANC_CONTAINER" >/dev/null 2>&1 || true
docker run -d --name "$ORTHANC_CONTAINER" --network "$NETWORK" -p "127.0.0.1:$ORTHANC_PORT:8042" \
  -e ORTHANC_PASSWORD="$ORTHANC_PASSWORD" -e TZ=UTC \
  -v "$ROOT/infra/orthanc/orthanc.json:/etc/orthanc/orthanc.json:ro" \
  "orthancteam/orthanc@$DIGEST" >/dev/null
wait_for "image node" 120 curl -fsu "orthanc:$ORTHANC_PASSWORD" "http://127.0.0.1:$ORTHANC_PORT/system"

say "migrations"
(cd "$ROOT/packages/db" && pnpm exec tsx src/migrate.ts) | tail -1

say "bootstrap owner ops@test.local, tenant whq, node node-test"
# The node URL is the loopback port this script published, not the container name: the api
# and the worker run on the host here, and a host process cannot resolve `tr-orth`. The
# viewer reads this column, so getting it wrong looks like a broken viewer rather than a
# wrong fixture.
(cd "$ROOT/apps/api" && pnpm exec tsx src/cli.ts bootstrap \
  --email ops@test.local --name "Ops Owner" --password "$PASSPHRASE" \
  --node-id node-test --node-url "http://127.0.0.1:$ORTHANC_PORT" --node-aet TELRAD_TEST \
  --tenant-code whq --tenant-name "WebHQ Diagnostics") | tail -1

# Three readers, and the grades are the point: Green holds and signs, Junior may read but
# may neither clear nor amend, Second is the chief who clears and then corrects. The
# registration numbers are asserted verbatim by the flows, so they belong here and not in a
# note.
say "readers"
(cd "$ROOT/apps/api" && pnpm exec tsx src/cli.ts add-reader \
  --email dr-green@test.local --name "Dr Green" --password "$PASSPHRASE" \
  --grade senior --role radiologist --tenant 1 --subs ct-head,dx-chest --mods CT,DX \
  --council WB --reg-no WB-100001 --states WB --max-queue 3) | tail -1
(cd "$ROOT/apps/api" && pnpm exec tsx src/cli.ts add-reader \
  --email dr-second@test.local --name "Dr Second" --password "$PASSPHRASE" \
  --grade chief --role reviewer --tenant 1 --subs '*' --mods '*' \
  --council WB --reg-no WB-200002 --states WB --max-queue 5) | tail -1
(cd "$ROOT/apps/api" && pnpm exec tsx src/cli.ts add-reader \
  --email dr-junior@test.local --name "Dr Junior" --password "$PASSPHRASE" \
  --grade junior --role radiologist --tenant 1 --subs ct-head --mods CT \
  --council WB --reg-no WB-300003 --states WB --max-queue 5) | tail -1
# A second chief, because the flow's amendment makes Dr Second the author of v2 and an
# author cannot be their own second name. Without a peer nobody can clear the corrected
# version, so delivery of a corrected report could only be argued about, not run.
(cd "$ROOT/apps/api" && pnpm exec tsx src/cli.ts add-reader \
  --email dr-boss@test.local --name "Dr Boss" --password "$PASSPHRASE" \
  --grade chief --role radiologist --tenant 1 --subs '*' --mods '*' \
  --council WB --reg-no WB-500005 --states WB --max-queue 5) | tail -1

say "api on 127.0.0.1:$API_PORT (log: $RUNTIME/api.log)"
api_start

say "up. source it with:  source $RUNTIME/env.sh"
